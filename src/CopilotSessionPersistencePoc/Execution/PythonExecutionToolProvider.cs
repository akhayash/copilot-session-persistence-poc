using System.ComponentModel;
using CopilotSessionPersistencePoc.Copilot;
using GitHub.Copilot;
using Microsoft.Extensions.AI;

namespace CopilotSessionPersistencePoc.Execution;

public sealed class PythonExecutionToolProvider(
    PythonExecutionCoordinator coordinator)
    : ICopilotToolProvider
{
    public IReadOnlyList<AIFunction> CreateTools(string sessionId) =>
    [
        CopilotTool.DefineTool(
            async (ToolInvocation invocation, CancellationToken cancellationToken) =>
            {
                EnsureSession(invocation, sessionId);
                return await coordinator.ListArtifactsAsync(
                    sessionId,
                    cancellationToken);
            },
            toolOptions: new CopilotToolOptions
            {
                Defer = CopilotToolDefer.Never,
                SkipPermission = true,
            },
            factoryOptions: new AIFunctionFactoryOptions
            {
                Name = "list_artifacts",
                Description =
                    "List files uploaded to or generated by the current chat session. "
                    + "Use artifactId/fileName values as execute_python inputs.",
            }),
        CopilotTool.DefineTool(
            async (
                [Description("Python source code to run.")] string code,
                [Description(
                    "Artifact references in artifactId/fileName format to upload into /mnt/data.")]
                string[]? inputFiles,
                ToolInvocation invocation,
                CancellationToken cancellationToken) =>
            {
                EnsureSession(invocation, sessionId);
                return await coordinator.ExecuteAsync(
                    sessionId,
                    invocation.ToolCallId,
                    code,
                    inputFiles,
                    cancellationToken);
            },
            toolOptions: new CopilotToolOptions
            {
                Defer = CopilotToolDefer.Never,
                SkipPermission = true,
            },
            factoryOptions: new AIFunctionFactoryOptions
            {
                Name = "execute_python",
                Description =
                    "Run Python with common data and document packages, including "
                    + "python-pptx, in an isolated environment. Packages are preinstalled; "
                    + "do not run pip. Read inputs from /mnt/data and write every "
                    + "downloadable result directly under /mnt/data. Files written under "
                    + "/session-state are not returned.",
            }),
    ];

    private static void EnsureSession(ToolInvocation invocation, string expectedSessionId)
    {
        if (!string.Equals(
            invocation.SessionId,
            expectedSessionId,
            StringComparison.Ordinal))
        {
            throw new InvalidOperationException(
                "The tool invocation does not belong to the active session.");
        }

        ArgumentException.ThrowIfNullOrWhiteSpace(invocation.ToolCallId);
    }
}
